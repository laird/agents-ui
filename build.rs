//! Generates the village's embedded asset list (#447).
//!
//! Every file under `src/web/village/` is embedded in the binary and served
//! at `/village/<path>`. Rather than a hand-written `include_str!` per file in
//! `src/web/server.rs`, this walks the directory and writes
//! `$OUT_DIR/village_assets.rs`: one `(path, content type, contents)` per
//! file, sorted by path, which `server.rs` includes as `VILLAGE_ASSETS`.
//! Adding a file under `src/web/village/` then needs no edit anywhere else.

use std::fs;
use std::path::{Path, PathBuf};

const VILLAGE_DIR: &str = "src/web/village";

/// The content type each kind of village file is served with. A file of any
/// other kind stops the build: guessing would serve it wrong without a word.
fn content_type(path: &str) -> Option<&'static str> {
    match path.rsplit_once('.')?.1 {
        "html" => Some("text/html; charset=utf-8"),
        "css" => Some("text/css; charset=utf-8"),
        "js" => Some("text/javascript; charset=utf-8"),
        _ => None,
    }
}

/// Every file under `dir`, as paths relative to `root` with `/` separators.
/// Dotfiles (editor swap files and the like) are not part of the page.
fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, out);
        } else {
            let rel = path.strip_prefix(root).unwrap();
            let parts: Vec<String> = rel.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect();
            out.push(parts.join("/"));
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed={VILLAGE_DIR}");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join(VILLAGE_DIR);
    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    files.sort();

    let mut src = String::from(
        "/// Generated by build.rs from every file under src/web/village/: `(path, content type, contents)`, sorted by path.\n\
         const VILLAGE_ASSETS: &[(&str, &str, &str)] = &[\n",
    );
    for file in &files {
        let ty = content_type(file).unwrap_or_else(|| {
            panic!(
                "{VILLAGE_DIR}/{file}: no content type for this kind of file. \
                 The village serves .html, .css and .js; add the extension to content_type() in build.rs to embed it."
            )
        });
        let abs = root.join(file);
        src.push_str(&format!("    ({file:?}, {ty:?}, include_str!({:?})),\n", abs.to_string_lossy()));
    }
    src.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("village_assets.rs");
    fs::write(&out, src).unwrap_or_else(|e| panic!("write {}: {e}", out.display()));
}
