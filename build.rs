//! Generates the village's embedded asset list (#447).
//!
//! Every file under `src/web/village/` is embedded in the binary and served
//! at `/village/<path>`. Rather than a hand-written `include_str!` per file in
//! `src/web/server.rs`, this walks the directory and writes
//! `$OUT_DIR/village_assets.rs`: one `(path, content type, contents)` per
//! file, sorted by path, which `server.rs` includes as `VILLAGE_ASSETS`.
//! Adding a file under `src/web/village/` then needs no edit anywhere else.
//!
//! It also writes the page's module list (#520): `modules.js`, served like the
//! others but not on disk, imports every script under `src/web/village/` but
//! `main.js`, sorted by path. `main.js` imports the themes and `layout.js`
//! first, then `modules.js`, so a new module loads without an edit to any
//! shared file. The browser runs each module after its own imports, so that
//! order is all the page needs: what a feature draws with, it imports, and
//! where several modules register into one list (the key's groups, the
//! labels), each gives an explicit `order` (`tools/village-tests/
//! loadorder.test.mjs` holds them to distinct ones). `tools/mock/
//! replay-build.py` and the node tests (`tools/village-tests/modules.mjs`)
//! build the same list by the same rule.

use std::fs;
use std::path::{Path, PathBuf};

const VILLAGE_DIR: &str = "src/web/village";

/// The content type each kind of village file is served with. A file of any
/// other kind stops the build: guessing would serve it wrong without a word.
fn content_type(path: &str) -> Option<&'static str> {
    match path.rsplit_once('.')?.1 {
        "html" => Some("text/html; charset=utf-8"),
        "css" => Some("text/css; charset=utf-8"),
        "js" => Some("text/javascript; charset=utf-8"),
        _ => None,
    }
}

/// Every file under `dir`, as paths relative to `root` with `/` separators.
/// Dotfiles (editor swap files and the like) are not part of the page.
fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, out);
        } else {
            let rel = path.strip_prefix(root).unwrap();
            let parts: Vec<String> = rel.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect();
            out.push(parts.join("/"));
        }
    }
}

/// The generated module list's served path; no file may take it.
const MODULES: &str = "modules.js";

/// `modules.js`: an import of each script but `main.js`, in `files`' order.
fn module_list(files: &[String]) -> String {
    let mut src = String::from(
        "/* Generated by build.rs (#520): every module under src/web/village/ but main.js,\n \
         * sorted by path. main.js imports the themes and layout.js, then this. */\n",
    );
    for f in files.iter().filter(|f| f.ends_with(".js") && f.as_str() != "main.js") {
        src.push_str(&format!("import './{f}';\n"));
    }
    src
}

fn main() {
    println!("cargo:rerun-if-changed={VILLAGE_DIR}");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join(VILLAGE_DIR);
    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    files.sort();

    let mut src = String::from(
        "/// Generated by build.rs from every file under src/web/village/, and the module list modules.js: `(path, content type, contents)`, sorted by path.\n\
         const VILLAGE_ASSETS: &[(&str, &str, &str)] = &[\n",
    );
    if files.iter().any(|f| f == MODULES) {
        panic!("{VILLAGE_DIR}/{MODULES}: build.rs generates the page's module list under this name; rename the file.");
    }
    let modules = module_list(&files);
    let mut rows: Vec<(String, String)> = Vec::new();
    for file in &files {
        let ty = content_type(file).unwrap_or_else(|| {
            panic!(
                "{VILLAGE_DIR}/{file}: no content type for this kind of file. \
                 The village serves .html, .css and .js; add the extension to content_type() in build.rs to embed it."
            )
        });
        let abs = root.join(file);
        rows.push((file.clone(), format!("    ({file:?}, {ty:?}, include_str!({:?})),\n", abs.to_string_lossy())));
    }
    rows.push((MODULES.to_string(), format!("    ({MODULES:?}, {:?}, {modules:?}),\n", content_type(MODULES).unwrap())));
    rows.sort();
    for (_, row) in rows {
        src.push_str(&row);
    }
    src.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("village_assets.rs");
    fs::write(&out, src).unwrap_or_else(|e| panic!("write {}: {e}", out.display()));
}
