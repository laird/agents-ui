    /// Every file under `src/web/village/` is embedded and served (#447):
    /// the list is generated from the directory, so none can be left out.
    #[tokio::test]
    async fn every_file_under_village_is_served() {
        fn walk(root: &std::path::Path, dir: &std::path::Path, out: &mut Vec<String>) {
            for entry in std::fs::read_dir(dir).unwrap() {
                let path = entry.unwrap().path();
                if path.file_name().unwrap().to_string_lossy().starts_with('.') {
                    continue;
                }
                if path.is_dir() {
                    walk(root, &path, out);
                } else {
                    let rel = path.strip_prefix(root).unwrap();
                    out.push(rel.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/"));
                }
            }
        }
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/web/village");
        let mut files = Vec::new();
        walk(&root, &root, &mut files);
        files.sort();
        let embedded: Vec<&str> = VILLAGE_ASSETS.iter().map(|(p, _, _)| *p).collect();
        assert_eq!(embedded, files, "VILLAGE_ASSETS is every file under src/web/village/, sorted");
        assert!(files.len() >= 35 && files.iter().any(|f| f.contains('/')), "subdirectories included: {files:?}");
        for path in files.iter().filter(|p| *p != "index.html") {
            let app = make_app(make_web_state(new_shared_state()));
            let resp = app.oneshot(Request::builder().uri(format!("/village/{path}")).body(Body::empty()).unwrap()).await.unwrap();
            assert_eq!(resp.status(), StatusCode::OK, "{path}");
            let body = axum::body::to_bytes(resp.into_body(), usize::MAX).await.unwrap();
            assert_eq!(body, std::fs::read(root.join(path)).unwrap(), "{path} is served as it is on disk");
        }
        // The page itself is /village.
        let app = make_app(make_web_state(new_shared_state()));
        let resp = app.oneshot(Request::builder().uri("/village").body(Body::empty()).unwrap()).await.unwrap();
        assert_eq!(resp.status(), StatusCode::OK);
        assert_eq!(resp.headers()["content-type"], "text/html; charset=utf-8");
    }

    /// The files a village module imports, as paths under `village/`:
    /// `import { P } from '../palette.js';` in `themes/modern.js` is `palette.js`.
    fn village_imports(path: &str, body: &str) -> Vec<String> {
        let dir: Vec<&str> = path.split('/').collect::<Vec<_>>()[..path.matches('/').count()].to_vec();
        body.lines()
            .filter(|l| l.starts_with("import "))
            .filter_map(|l| l.split(['\'', '"']).nth(1))
            .map(|spec| {
                let mut parts = dir.clone();
                for seg in spec.split('/') {
                    match seg {
                        "." => {}
                        ".." => { parts.pop(); }
                        s => parts.push(s),
                    }
                }
                parts.join("/")
            })
            .collect()
    }

